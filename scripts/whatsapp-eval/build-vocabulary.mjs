#!/usr/bin/env node
/**
 * Turns the phrase lists in scripts/whatsapp-eval/lexicon/*.json into the
 * vocabulary the bot uses at runtime (src/lib/whatsapp-vocabulary.ts):
 * every Hebrew and English word customers use, Hebrew written in English
 * letters, and the words that signal a rental, an emergency, a complaint or
 * a request for a person.
 *
 *   node scripts/whatsapp-eval/build-vocabulary.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const read = (name) => {
  try {
    return JSON.parse(readFileSync(new URL(`./lexicon/${name}.json`, import.meta.url), 'utf8'));
  } catch {
    return {};
  }
};

const rental = read('rental');
const questions = read('questions');
const urgent = read('urgent');
const language = read('language');

const allEntries = [rental, questions, urgent, language].flatMap((file) => Object.values(file));
const strings = (language) => allEntries.flatMap((entry) => (Array.isArray(entry?.[language]) ? entry[language] : []));

const hebrewWord = /[א-ת][א-ת׳'"״]*/g;
const englishWord = /[a-z][a-z']*/g;

function counted(texts, pattern) {
  const counts = new Map();
  for (const text of texts) for (const word of text.toLowerCase().match(pattern) ?? []) {
    const clean = word.replace(/["'׳״]/g, '');
    if (clean.length >= 2) counts.set(clean, (counts.get(clean) ?? 0) + 1);
  }
  return counts;
}

const hebrewCounts = counted([...strings('he'), ...(language.hebrew_common_words ?? []), ...Object.values(language.transliteration ?? {})], hebrewWord);
const englishCounts = counted([...strings('en'), ...(language.english_common_words ?? [])], englishWord);
const top = (counts, limit) => [...counts].sort((a, b) => b[1] - a[1]).slice(0, limit).map(([word]) => word).sort();

const hebrew = top(hebrewCounts, 8000);
const english = top(englishCounts, 5000);

const transliteration = Object.fromEntries(Object.entries(language.transliteration ?? {})
  .filter(([latin, hebrewText]) => /^[a-z]+$/.test(latin) && latin.length >= 2 && /[א-ת]/.test(hebrewText))
  .sort(([a], [b]) => a.localeCompare(b)));

const keywordGroups = {};
for (const item of [...(urgent.key_words?.he ?? []), ...(urgent.key_words?.en ?? [])]) {
  const [group, ...rest] = item.split(':');
  const word = rest.join(':').trim().toLowerCase().replace(/["'׳״]/g, '');
  if (word) (keywordGroups[group] ??= new Set()).add(word);
}

const clean = (list) => [...new Set((list ?? []).map((w) => w.trim().toLowerCase().replace(/["'׳״]/g, '')).filter(Boolean))].sort();

const out = `// Generated by scripts/whatsapp-eval/build-vocabulary.mjs from scripts/whatsapp-eval/lexicon/*.json.
// Do not edit by hand: change the lexicon files and run the script again.

/** Hebrew words customers use (${hebrew.length}). */
export const HEBREW_VOCABULARY: readonly string[] = ${JSON.stringify(hebrew)};

/** English words customers use (${english.length}). */
export const ENGLISH_VOCABULARY: readonly string[] = ${JSON.stringify(english)};

/** Hebrew written in English letters → Hebrew (${Object.keys(transliteration).length}). */
export const TRANSLITERATED_HEBREW: Readonly<Record<string, string>> = ${JSON.stringify(transliteration)};

/** Words and phrases that signal each kind of message. */
export const INTENT_KEYWORDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(Object.fromEntries(Object.entries(keywordGroups).map(([group, words]) => [group, [...words].sort()])))};

/** Ways to say "a car" and "I want / need / book", for recognising a rental. */
export const VEHICLE_WORDS: readonly string[] = ${JSON.stringify(clean([...(rental.vehicle_words?.he ?? []), ...(rental.vehicle_words?.en ?? [])]))};
export const WANT_WORDS: readonly string[] = ${JSON.stringify(clean([...(rental.want_words?.he ?? []), ...(rental.want_words?.en ?? [])]))};
`;

writeFileSync(new URL('../../src/lib/whatsapp-vocabulary.ts', import.meta.url), out);
console.log(`Hebrew ${hebrew.length}, English ${english.length}, transliteration ${Object.keys(transliteration).length}, keyword groups ${Object.keys(keywordGroups).join('/')}`);
