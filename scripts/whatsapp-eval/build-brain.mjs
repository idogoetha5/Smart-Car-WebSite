#!/usr/bin/env node
/**
 * Compiles the brain phrase lists (scripts/whatsapp-eval/lexicon/brain/*.json)
 * into src/lib/whatsapp-brain-data.ts, which whatsapp-brain.ts and
 * whatsapp-replies.ts read at runtime.
 *
 *   node scripts/whatsapp-eval/build-brain.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const dir = new URL('./lexicon/brain/', import.meta.url);
const read = (name) => (existsSync(new URL(`${name}.json`, dir)) ? JSON.parse(readFileSync(new URL(`${name}.json`, dir), 'utf8')) : {});
const uniq = (list) => [...new Set((list ?? []).map((s) => String(s).trim()).filter(Boolean))];

const situationsRaw = read('situations');
const situations = Object.fromEntries(Object.entries(situationsRaw).map(([key, value]) => [key, uniq([...(value.he ?? []), ...(value.en ?? []), ...(value.translit ?? [])])]));

const placesRaw = read('places');
const places = (placesRaw.places ?? []).filter((p) => p?.name).map((p) => ({ name: String(p.name).trim(), en: String(p.en ?? '').trim(), spellings: uniq(p.spellings) }));

const vehiclesRaw = read('vehicles');
// "pick up" is how customers say they collect the car, not a pickup truck.
const NOT_A_CAR = /^(?:pick ?-?up|פיק ?אפ|איסוף|לאסוף)$/i;
const vehicleCategories = Object.fromEntries(Object.entries(vehiclesRaw.categories ?? {}).map(([cat, value]) => [cat, uniq([...(value.he ?? []), ...(value.en ?? [])]).filter((p) => !NOT_A_CAR.test(p.trim()) && /[\p{L}]/u.test(p) && (cat !== 'ALL' || p.trim().includes(' ')))]));
const models = (vehiclesRaw.models ?? []).filter((m) => m?.model && m?.category).map((m) => ({ model: m.model, category: m.category, spellings: uniq(m.spellings).filter((p) => /[\p{L}]/u.test(p)) }));
const passengers = ((vehiclesRaw.passengers?.phrases) ?? vehiclesRaw.passengers ?? []).filter((p) => p?.text && Number.isFinite(p.count) && p.count > 0 && p.count <= 20)
  .map((p) => ({ text: String(p.text), count: p.count }))
  .sort((a, b) => b.text.length - a.text.length);

const datesRaw = read('dates');
// Only precise words: today, tomorrow, the day after, or "in N days/weeks". "Next week" is a range, not a date.
const PRECISE = /\d|בעוד|עוד |in \d|in a |in one |in two |in three |היום|מחר|today|tomorrow|tmrw|machar|hayom/i;
const relativeDays = (datesRaw.relative_days ?? []).filter((r) => Number.isInteger(r.offset_days) && r.offset_days >= 0)
  .map((r) => ({ phrases: uniq(r.phrases).filter((p) => PRECISE.test(p) && !/הבא|next|this|הזה|^עד |^until /i.test(p)), offset_days: r.offset_days }))
  .filter((r) => r.phrases.length);
const durations = (datesRaw.durations ?? []).filter((d) => Number.isInteger(d.days) && d.days > 0 && d.days <= 60).map((d) => ({ phrases: uniq(d.phrases), days: d.days }));
const holidays = (datesRaw.holidays ?? []).filter((h) => h?.dates).map((h) => ({
  name: h.name,
  phrases: uniq(h.phrases),
  dates: Object.fromEntries(Object.entries(h.dates).filter(([, range]) => Array.isArray(range) && range.length === 2 && range.every((d) => /^\d{4}-\d{2}-\d{2}$/.test(d)))),
}));

const repliesRaw = read('replies');
const replies = Object.fromEntries(Object.entries(repliesRaw).map(([key, value]) => [key, {
  he: { open: value.he?.open ?? [], core: value.he?.core ?? [], close: value.he?.close ?? [] },
  en: { open: value.en?.open ?? [], core: value.en?.core ?? [], close: value.en?.close ?? [] },
}]));

const BRAIN = {
  situations, places, samePlace: uniq(placesRaw.same_place), deliverToMe: uniq(placesRaw.deliver_to_me),
  vehicleCategories, models, passengers, relativeDays, durations, holidays, replies,
};

const out = `// Generated by scripts/whatsapp-eval/build-brain.mjs from scripts/whatsapp-eval/lexicon/brain/*.json.
// Do not edit by hand: change the lexicon files and run the script again.

type Parts = { open: string[]; core: string[]; close: string[] };
export interface BrainData {
  situations: Record<string, string[]>;
  places: Array<{ name: string; en: string; spellings: string[] }>;
  samePlace: string[];
  deliverToMe: string[];
  vehicleCategories: Record<string, string[]>;
  models: Array<{ model: string; category: string; spellings: string[] }>;
  passengers: Array<{ text: string; count: number }>;
  relativeDays: Array<{ phrases: string[]; offset_days: number }>;
  durations: Array<{ phrases: string[]; days: number }>;
  holidays: Array<{ name: string; phrases: string[]; dates: Record<string, string[]> }>;
  replies: Record<string, { he: Parts; en: Parts }>;
}

export const BRAIN: BrainData = ${JSON.stringify(BRAIN)};
`;
writeFileSync(new URL('../../src/lib/whatsapp-brain-data.ts', import.meta.url), out);
const count = (o) => Object.values(o).reduce((s, l) => s + l.length, 0);
console.log(JSON.stringify({
  situations: count(situations), places: places.length, placeSpellings: places.reduce((s, p) => s + p.spellings.length, 0),
  vehiclePhrases: count(vehicleCategories), models: models.length, passengers: passengers.length,
  relativeDays: relativeDays.length, durations: durations.length, holidays: holidays.length, replySituations: Object.keys(replies).length,
}));
